#!/usr/bin/env python3
"""Generate src/ion-data.js. Run: python3 scripts/build-ion-data.py > src/ion-data.js
Source: NIST Atomic Spectra Database, Ground Levels and Ionization Energies, all stages H-Lr
https://physics.nist.gov/cgi-bin/ASD/ie.pl (column "Ground Shells"). Measured/evaluated by NIST for free gas-phase ions;
nothing is derived here. Entry ions[z][q-1] is the ground-state configuration of the ion with charge +q, or '' if NIST gives none.
Format: optional noble-gas core symbol, then space separated subshell tokens (e.g. 'Ar 3d6'), in filling (Madelung) order."""
import re,html,json,urllib.request
def get(u): return urllib.request.urlopen(urllib.request.Request(u,headers={'User-Agent':'Mozilla/5.0'}),timeout=120).read().decode('utf-8','ignore')
h=get('https://physics.nist.gov/cgi-bin/ASD/ie.pl?biblio=on&e_out=0&el_name_out=on&format=0&ion_charge_out=on&ion_conf_out=on&level_out=on&order=0&seq_out=on&shells_out=on&spectra=H-Lr+I'.replace('+I',''))
SUB='spdfghi'
def order(s):
    n,l=int(s[0]),SUB.index(s[1]);return (n+l,n)
GAS=[('He',2),('Ne',10),('Ar',18),('Kr',36),('Xe',54),('Rn',86)]
def tok(c):
    c=re.sub(r'<i>([spdf])</i><sup>(\d+)</sup>',r'\1\2,',c);c=re.sub(r'<i>([spdf])</i>',r'\g<1>1,',c)
    return re.sub(r'<[^>]+>','',c).replace('&nbsp;','').strip()
def parse(c):
    m=re.match(r'\[(\w+)\]',c);core=None
    if m: core=m.group(1);c=c[m.end():]
    return core,[(a+b,int(n)) for a,b,n in re.findall(r'(\d[spdf])(\w?)(\d*),',c) for b in [b]] if False else [(a+b,int(n)) for a,b,n in re.findall(r'(\d)([spdf])(\d+),',c)]
FULL={}
def expand(core):
    return dict(FULL[core]) if core else {}
ions={};z=0
for r in re.findall(r'<tr class="bsl">(.*?)</tr>',h,re.S):
    tds=re.findall(r'<td[^>]*>(.*?)</td>',r,re.S)
    q=int(re.sub(r'[^\d+\-]','',html.unescape(tds[0]).replace('\xa0','')) or 0)
    if q==0: z+=1;ions[z]=[]
    c=tok(tds[3]);core,t=parse(c);d=expand(core)
    for s,n in t:d[s]=d.get(s,0)+n
    if q==0:FULL[html.unescape(re.sub(r'<[^>]+>','',tds[2])).replace('\xa0','').strip()]=dict(d)
    N=z-q
    if q==0 or not d or sum(d.values())!=N:
        if q>0: ions[z].append('') 
        continue
    gas=''
    for name,nz in GAS:
        if name not in FULL: continue
        fd=FULL[name]
        if nz<N and all(d.get(s,0)>=n for s,n in fd.items()):gas=name
    if gas:
        for s,n in FULL[gas].items():
            d[s]-=n
            if d[s]==0:del d[s]
    ions[z].append((gas+' ' if gas else '')+' '.join(s+str(d[s]) for s in sorted(d,key=order)))
assert z==103,z
print('// Generated by scripts/build-ion-data.py. Do not edit by hand.')
print('// Ground-state configurations of free gas-phase cations, Z<=103: NIST Atomic Spectra Database ground shells. ions[z][q-1] is the ion with charge +q; empty string means NIST gives none.')
print('export const ions='+json.dumps([None]+[ions[i] for i in range(1,104)],separators=(',',':'))+';')
