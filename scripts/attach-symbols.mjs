let src = fs.readFileSync(new URL('../src/reference-formulas.js',import.meta.url),'utf8');
const labels = new Map();
for(const c of courses)for(const t of c.topics)for(const item of t.items)labels.set(t.id+'/'+item[0],item);

let applied=0;
for(const [key,ids] of Object.entries(A)){
  const item=labels.get(key);
  if(!item){console.error('NO SUCH ITEM',key);process.exitCode=1;continue}
  for(const id of ids)if(!SYMBOLS[id]){console.error('UNKNOWN SYMBOL',key,id);process.exitCode=1}
  const [label,expr,note]=item;
  if(typeof expr!=='string'){console.error('OBJECT ITEM',key);process.exitCode=1;continue}
  const old=`['${label}','${expr}'${note!==undefined?`,'${note}'`:''}]`;
  const count=src.split(old).length-1;
  if(count!==1){console.error('MATCHES',count,key);process.exitCode=1;continue}
  src=src.replace(old,`['${label}','${expr}'${note!==undefined?`,'${note}'`:''},[${ids.map(i=>`'${i}'`).join(',')}]]`);
  applied++;
}
console.log('applied',applied,'of',Object.keys(A).length);
fs.writeFileSync(new URL('../src/reference-formulas.js',import.meta.url),src);
